function checkSourceOverlap(draftText, scenes, limit = 10) {
  if (!String(draftText || '').trim()) throw Object.assign(new Error('待检查正文为空'), { code: 'SOURCE_TEXT_MISSING' });
  const searchableScenes = Array.isArray(scenes)
    ? scenes.filter(scene => scene && typeof scene.text === 'string' && compact(scene.text).length >= 36)
    : [];
  if (!searchableScenes.length) throw Object.assign(new Error('题材原文语料不可用，无法执行重合检查'), { code: 'SOURCE_CORPUS_UNAVAILABLE' });
  const normalizedDraft = compact(draftText);
  if (normalizedDraft.length < 36) throw Object.assign(new Error('待检查正文不足36字，无法执行重合检查'), { code: 'SOURCE_TEXT_TOO_SHORT' });

  const candidateMap = [];
  searchableScenes.forEach(scene => {
    const norm = compact(scene.text);
    if (norm.length >= 36) {
      candidateMap.push({ id: scene.id, title: scene.title || '', norm });
    }
  });
  if (!candidateMap.length) throw Object.assign(new Error('题材原文语料没有可检查片段'), { code: 'SOURCE_CORPUS_UNAVAILABLE' });

  const issues = [];
  const matchedScenes = new Set();

  for (let offset = 0; offset <= normalizedDraft.length - 24; offset += 6) {
    const gram = normalizedDraft.slice(offset, offset + 24);
    for (const cand of candidateMap) {
      if (matchedScenes.has(cand.id)) continue;
      const candOffset = cand.norm.indexOf(gram);
      if (candOffset < 0) continue;

      let left = 0, right = 24;
      while (offset - left > 0 && candOffset - left > 0 && normalizedDraft[offset - left - 1] === cand.norm[candOffset - left - 1]) left++;
      while (offset + right < normalizedDraft.length && candOffset + right < cand.norm.length && normalizedDraft[offset + right] === cand.norm[candOffset + right]) right++;

      if (left + right >= 36) {
        matchedScenes.add(cand.id);
        issues.push({
          code: 'source_overlap',
          severity: 'blocker',
          length: left + right,
          evidence: normalizedDraft.slice(offset - left, offset + right),
          sourceId: cand.id,
          sourceTitle: cand.title
        });
      }
    }
    if (issues.length >= limit) break;
  }
  return issues;
}

/** 将重合检测结果与语料可用状态一起返回，避免空库被当成通过。 */
function inspectSourceOverlap(draftText, scenes, limit = 10) {
  if (!String(draftText || '').trim()) {
    return { available: false, passed: false, status: 'incomplete', reason: 'source_text_missing', issues: [] };
  }
  const searchableScenes = Array.isArray(scenes)
    ? scenes.filter(scene => scene && typeof scene.text === 'string' && compact(scene.text).length >= 36)
    : [];
  if (!searchableScenes.length) {
    return { available: false, passed: false, status: 'incomplete', reason: 'source_corpus_unavailable', issues: [] };
  }
  if (compact(draftText).length < 36) {
    return { available: true, passed: false, status: 'incomplete', reason: 'source_text_too_short', issues: [] };
  }
  const issues = checkSourceOverlap(draftText, searchableScenes, limit);
  return {
    available: true,
    sceneCount: searchableScenes.length,
    passed: issues.length === 0,
    status: issues.length ? 'needs_review' : 'passed',
    reason: issues.length ? 'source_overlap' : '',
    issues
  };
}

/** 章节划分正则与切分 */
function extractChapterRanges(text) {
  const pattern = /^[ \t]*(?:第[零〇一二三四五六七八九十百千万两\d]+[章节回卷][^\r\n]{0,65}|\d{1,5}[、.．][ \t]*[^\r\n]{1,65}|\d{3,5}[\u4e00-\u9fff][^\r\n]{0,55})[ \t]*$/gm;
  const headings = [...text.matchAll(pattern)].map(match => ({ title: match[0].trim(), start: match.index + match[0].length }));
  return headings.map((heading, index) => ({
    ...heading,
    end: index + 1 < headings.length ? headings[index + 1].start - headings[index + 1].title.length : text.length
  })).filter(chapter => chapter.end - chapter.start > 600);
}

/** 从章节中提取 1400-3400 字符的高张力场景切片 */
function extractSceneWindows(text, chapter) {
  const body = text.slice(chapter.start, chapter.end);
  const paragraphs = [...body.matchAll(/[^\r\n]+/g)].filter(match => match[0].trim());
  const windows = [];
  let start = null;
  for (const p of paragraphs) {
    if (start === null) start = p.index;
    const end = p.index + p[0].length;
    if (end - start < 1400) continue;
    if (end - start <= 3400) {
      windows.push({ start: chapter.start + start, end: chapter.start + end, text: body.slice(start, end).trim() });
    }
    start = null;
  }
  return windows;
}

/** 文本自动编码探测 */
function decodeTextBuffer(buffer) {
  let text = buffer.toString('utf8');
  let encoding = 'utf8';
  if ((text.match(/\uFFFD/g) || []).length > 8) {
    try {
      text = new TextDecoder('gb18030').decode(buffer);
      encoding = 'gb18030';
    } catch (_) {
      try {
        text = new TextDecoder('gbk').decode(buffer);
        encoding = 'gbk';
      } catch (_) {}
    }
  }
  return { text, encoding };
}

