/** 动态匹配模块化经典功能场景切片（交易/潜伏/交锋/勘验） */
function matchDynamicSceneSlice(query, genre = '') {
  const lib = loadSceneSlices();
  if (!lib || !lib.categories) return null;
  const text = (String(query || '') + ' ' + String(genre || '')).toLowerCase();

  let targetCategory = 'trade';
  if (/潜伏|受伤|包扎|屏息|泥|芦苇|躲|门后|暗杀|追杀|隐匿|沼泽|伏击/.test(text)) {
    targetCategory = 'stealth';
  } else if (/酒席|敬酒|公堂|官场|对质|座次|机锋|对牌|对峙|破庙|博弈|审理|少卿|衙门/.test(text)) {
    targetCategory = 'confrontation';
  } else if (/勘验|验尸|死相|水浸|水线|溺水|指甲|泥沙|衣扣|凶手|法医|伤口|仵作|骨折/.test(text)) {
    targetCategory = 'forensics';
  } else if (/黑市|当铺|拍卖|估价|买卖|交易|换|灵石|银子|出价|压价|朝奉|死当|竞价/.test(text)) {
    targetCategory = 'trade';
  }

  const cat = lib.categories[targetCategory];
  if (!cat || !cat.slices || !cat.slices.length) return null;

  let bestSlice = cat.slices[0];
  let maxScore = -1;
  for (const sl of cat.slices) {
    let score = 0;
    for (const tag of sl.tags) {
      if (text.includes(tag.toLowerCase())) score += 2;
    }
    if (score > maxScore) {
      maxScore = score;
      bestSlice = sl;
    }
  }
  return { categoryKey: targetCategory, categoryName: cat.name, slice: bestSlice };
}

/** 检索高相关性高张力范文切片 */
function retrieveCorpusScenes(familyId, query, limit = 3, { sourceTitle = '' } = {}) {
  const corpus = loadCorpusForFamily(familyId);
  let scenes = Array.isArray(corpus.scenes)
    ? corpus.scenes.filter(scene => scene && typeof scene.text === 'string' && compact(scene.text).length >= 36)
    : [];
  if (sourceTitle) {
    scenes = scenes.filter(scene => scene.title === sourceTitle || scene.title.includes(sourceTitle) || sourceTitle.includes(scene.title));
  }
  if (!scenes.length) return [];

  const tokens = String(query || '').toLowerCase().match(/[\u4e00-\u9fa5]{2,6}|[a-z0-9]{2,10}/g) || [];
  if (!tokens.length) return scenes.slice(0, limit);

  const scored = scenes.map(scene => {
    let score = 0;
    const textLower = scene.text.toLowerCase();
    for (const tok of tokens) {
      if (textLower.includes(tok)) score += 2;
    }
    for (const f of scene.functions || []) {
      for (const tok of tokens) {
        if (f.includes(tok)) score += 3;
      }
    }
    return { scene, score };
  });

  const matched = scored.filter(item => item.score > 0);
  const pool = matched.length ? matched.sort((a, b) => b.score - a.score) : scored;
  return pool.slice(0, limit).map(item => item.scene);
}

