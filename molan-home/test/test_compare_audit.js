  const flavor1 = computeAiFlavorScore(draftV1);
  console.log(`- 纠错命中数: ${audit1.findingCount}`);
  console.log(`- 命中规则清单: ${audit1.matchedRuleIds.join(', ')}`);
  console.log(`- AI 味综合评分: ${flavor1.score} 分 (门禁合格线 < 40)`);
