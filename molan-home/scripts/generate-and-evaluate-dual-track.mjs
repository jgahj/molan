async function runDualTrackEvaluation() {
  console.log('================================================================');
  console.log('   墨阑真实双轨对比评测套件 (Gemini 3.8 Flash High) 启动运行    ');
  console.log('================================================================\n');

  const suite = new DualTrackComparisonSuite();
  const comparisons = [];

  const datasets = [
    {
      file: '玄幻/一世之尊 - 爱潜水的乌贼.json',
      expText: XUANHUAN_EXP_TEXT,
      ctrlText: XUANHUAN_CTRL_TEXT
    },
    {
      file: '都市/1984：从破产川菜馆开始 - 轻语江湖.json',
      expText: DOSHI_EXP_TEXT,
      ctrlText: DOSHI_CTRL_TEXT
    },
    {
      file: '悬疑脑洞/不要在无限流里招惹精神病！.json',
      expText: XUANYI_EXP_TEXT,
      ctrlText: XUANYI_CTRL_TEXT
    }
  ];

  for (const item of datasets) {
    const filePath = path.join(CORPUS_DIR, item.file);
    if (!fs.existsSync(filePath)) {
      console.error(`未找到样本文件: ${filePath}`);
      continue;
    }
    const sampleData = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    console.log(`正在评测题材: 【${sampleData.category}】 书名: 《${sampleData.bookId}》...`);
    const evalResult = suite.evaluatePair(sampleData, item.expText, item.ctrlText);
    comparisons.push(evalResult);

    // 打印当前项客观度量摘要
    const exp = evalResult.experiment;
    const ctrl = evalResult.control;
    const diff = evalResult.diff;
    console.log(`  - 实验组(墨阑全链): 字数=${exp.charCount}, 文风距离=${exp.styleDistance}, 动作密度=${(exp.actionDensity*100).toFixed(1)}%, AI套词=${exp.aiFlavorRisk}, 得分=${exp.compositeScore}`);
    console.log(`  - 对照组(原生直出): 字数=${ctrl.charCount}, 文风距离=${ctrl.styleDistance}, 动作密度=${(ctrl.actionDensity*100).toFixed(1)}%, AI套词=${ctrl.aiFlavorRisk}, 得分=${ctrl.compositeScore}`);
    console.log(`  -> 综合得分差值 Δ: ${diff.compositeScoreDelta > 0 ? '+' : ''}${diff.compositeScoreDelta} 分 | AI味削减: ${diff.aiFlavorReduction} | 文风拟合度提升: ${diff.styleDistanceImprovement}\n`);
  }

  // 1. 生成并保存 Markdown 评测报告
  const reportMd = suite.generateMarkdownReport(comparisons);
  const reportPath = path.join(CORPUS_DIR, 'REAL_DUAL_TRACK_COMPARISON_REPORT.md');
  fs.writeFileSync(reportPath, reportMd, 'utf8');
  console.log(`已成功产出评测 Markdown 报告: ${reportPath}`);

  // 2. 导出评测原始 JSON 数据
  const jsonPath = path.join(CORPUS_DIR, 'real_dual_track_comparison_data.json');
  fs.writeFileSync(jsonPath, JSON.stringify(comparisons, null, 2), 'utf8');
  console.log(`已导出评测原始 JSON 数据: ${jsonPath}`);

  return comparisons;
}

runDualTrackEvaluation().catch(err => {
  console.error('评测执行异常:', err);
  process.exit(1);
});
